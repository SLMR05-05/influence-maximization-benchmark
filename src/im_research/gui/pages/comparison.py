#!/usr/bin/env python3
"""Comparison Page — Measured Performance & Paired Statistical Tests.

Every number on this page is read from real experiment runs stored in
``runs/``.  Metrics that an experiment did not record are rendered as "—" and
excluded from rankings, Pareto frontiers and significance tests.  No composite
score, CPI or sample/demo value is generated by the GUI.
"""
import math
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Tuple

PROJECT_ROOT = Path(__file__).resolve().parents[4]
if str(PROJECT_ROOT / "src") not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT / "src"))

import customtkinter as ctk

from im_research.gui.core.theme import *
from im_research.gui.core.ui_helpers import section_header, create_empty_state
from im_research.gui.core.results_store import load_runs

try:
    from scipy.stats import wilcoxon as _wilcoxon
except Exception:  # pragma: no cover - depends on the runtime environment
    _wilcoxon = None

ALPHA = 0.05


def _number(value: Any) -> Optional[float]:
    """Returns a finite float, or None when the run did not record a value."""
    if value is None or isinstance(value, bool):
        return None
    try:
        number = float(value)
    except (TypeError, ValueError):
        return None
    return number if math.isfinite(number) else None


def _text(value: Any, digits: int = 2) -> str:
    if value is None:
        return "—"
    if isinstance(value, float):
        return f"{value:.{digits}f}"
    return str(value)


def _p_text(value: Optional[float]) -> str:
    if value is None:
        return "—"
    if value < 0.0001:
        return "< 0.0001"
    return f"{value:.4f}"


def _detail_for(run: Dict[str, Any], row: Dict[str, Any]) -> Dict[str, Any]:
    details = run.get("details") or {}
    detail = details.get(row.get("algorithm"))
    if isinstance(detail, dict):
        return detail
    code = str(row.get("code", "")).lower()
    for value in details.values():
        if isinstance(value, dict) and str(value.get("code", "")).lower() == code:
            return value
    return {}


def _spreads_for(run: Dict[str, Any], row: Dict[str, Any]) -> List[float]:
    detail = _detail_for(run, row)
    values = detail.get("spreads") or []
    if not values:
        values = [
            item.get("spread")
            for item in detail.get("runs_detail") or []
            if isinstance(item, dict)
        ]
    return [number for number in (_number(value) for value in values) if number is not None]


def _sample_count(run: Dict[str, Any], row: Dict[str, Any]) -> Optional[int]:
    """Number of independent repetitions recorded for this algorithm."""
    repetitions = _number(run.get("runs"))
    if repetitions is not None and repetitions > 0:
        return int(repetitions)
    spreads = _spreads_for(run, row)
    if spreads:
        return len(spreads)
    detail = _detail_for(run, row)
    times = detail.get("times") or []
    return len(times) if times else None


def _config_key(run: Dict[str, Any]) -> Tuple[str, str, str, str]:
    return (
        str(run.get("dataset", "")),
        str(run.get("k", "")),
        str(run.get("model", "")),
        str(run.get("mc", run.get("mc_val", ""))),
    )


def _config_label(run: Dict[str, Any]) -> str:
    parts = [
        str(run.get("dataset", "—")),
        f"k={run.get('k', '—')}",
        str(run.get("model", "—")),
        f"R={run.get('mc', run.get('mc_val', '—'))}",
    ]
    if run.get("timestamp"):
        parts.append(str(run.get("timestamp")))
    return " · ".join(parts)


class PageComparison(ctk.CTkScrollableFrame):
    def __init__(self, master, on_switch_tab=None, **kw):
        super().__init__(master, fg_color=BG_APP, **kw)
        self.on_switch_tab = on_switch_tab
        self._build()

    def on_show(self):
        self._refresh()

    def _refresh(self):
        for child in self.winfo_children():
            child.destroy()
        self._build()
        self.after(50, self._scroll_to_top)

    def _load_runs(self):
        try:
            return load_runs()
        except Exception:
            return []

    def _scroll_to_top(self):
        try:
            self._parent_canvas.yview_moveto(0.0)
        except Exception:
            pass

    # ── Real rows ────────────────────────────────────────────────────────────

    def _run_rows(self, run: Dict[str, Any], run_index: int) -> List[Dict[str, Any]]:
        """Returns summary and baseline rows, without duplicating algorithms."""
        rows: List[Dict[str, Any]] = []
        seen = set()

        for row in run.get("summary") or []:
            if not isinstance(row, dict):
                continue
            code = str(row.get("code", "")).lower()
            key = code or str(row.get("algorithm", ""))
            if key in seen:
                continue
            seen.add(key)
            rows.append(dict(row, _baseline=False, _run=run_index))

        for row in run.get("baseline") or []:
            if not isinstance(row, dict):
                continue
            code = str(row.get("code", "")).lower()
            key = code or str(row.get("algorithm", ""))
            if key in seen:
                continue
            seen.add(key)
            rows.append(dict(row, _baseline=True, _run=run_index))

        return rows

    def _prepare_rows(self, run: Dict[str, Any], run_index: int) -> List[Dict[str, Any]]:
        prepared: List[Dict[str, Any]] = []
        for row in self._run_rows(run, run_index):
            spread = _number(row.get("mean_spread"))
            prepared.append({
                "algorithm": row.get("algorithm", row.get("name", "N/A")),
                "code": str(row.get("code", "")).lower(),
                "baseline": bool(row.get("_baseline", False)),
                "run": run_index,
                "best": _number(row.get("best_spread")),
                "spread": spread,
                "std": _number(row.get("std_spread")),
                "time": _number(row.get("mean_time")),
                "samples": _sample_count(run, row),
                "rank": None,
                "pareto": None,
            })

        ranked = [item for item in prepared if item["spread"] is not None]
        ranked.sort(
            key=lambda item: (
                item["spread"],
                -(item["time"] if item["time"] is not None else math.inf),
            ),
            reverse=True,
        )
        previous_spread: Optional[float] = None
        previous_rank = 0
        for position, item in enumerate(ranked, start=1):
            if previous_spread is not None and abs(item["spread"] - previous_spread) < 1e-12:
                item["rank"] = previous_rank
            else:
                item["rank"] = position
                previous_spread = item["spread"]
                previous_rank = position

        # Pareto frontier: maximise spread, minimise measured time.  Items
        # missing either measurement are left undecided instead of defaulting
        # to zero (which used to create a fake "best" point).
        valid = [
            item for item in prepared
            if item["spread"] is not None and item["time"] is not None and item["time"] > 0
        ]
        for item in prepared:
            if item not in valid:
                continue
            item["pareto"] = not any(
                other is not item
                and other["spread"] >= item["spread"]
                and other["time"] <= item["time"]
                and (
                    other["spread"] > item["spread"]
                    or other["time"] < item["time"]
                )
                for other in valid
            )
        return prepared

    def _aggregate(self, prepared: Sequence[Dict[str, Any]]) -> List[Dict[str, Any]]:
        groups: Dict[str, List[Dict[str, Any]]] = {}
        for item in prepared:
            key = item["code"] or item["algorithm"]
            groups.setdefault(key, []).append(item)

        aggregated: List[Dict[str, Any]] = []
        for key, values in groups.items():
            def mean_of(field: str) -> Optional[float]:
                numbers = [item[field] for item in values if item[field] is not None]
                return sum(numbers) / len(numbers) if numbers else None

            samples = [item["samples"] for item in values if item["samples"] is not None]
            aggregated.append({
                "key": key,
                "algorithm": values[0]["algorithm"],
                "runs": len(values),
                "mean_spread": mean_of("spread"),
                "mean_std": mean_of("std"),
                "mean_time": mean_of("time"),
                "samples": sum(samples) if samples else None,
                "pareto": None,
            })

        valid = [
            item for item in aggregated
            if item["mean_spread"] is not None
            and item["mean_time"] is not None
            and item["mean_time"] > 0
        ]
        for item in aggregated:
            if item not in valid:
                continue
            item["pareto"] = not any(
                other is not item
                and other["mean_spread"] >= item["mean_spread"]
                and other["mean_time"] <= item["mean_time"]
                and (
                    other["mean_spread"] > item["mean_spread"]
                    or other["mean_time"] < item["mean_time"]
                )
                for other in valid
            )

        aggregated.sort(
            key=lambda item: (
                item["mean_spread"] is not None,
                item["mean_spread"] if item["mean_spread"] is not None else -math.inf,
            ),
            reverse=True,
        )
        return aggregated

    # ── Wilcoxon signed-rank tests ───────────────────────────────────────────

    def _test_run(self, runs: Sequence[Dict[str, Any]]):
        """Picks the run with the largest paired sample size for a reference."""
        samples: Dict[str, List[int]] = {}
        for run in runs:
            for code, values in self._spread_map(run).items():
                samples.setdefault(code, []).append(len(values))

        if not samples:
            return None, None, []

        largest = {code: max(values) for code, values in samples.items() if values}
        reference = (
            "iga" if largest.get("iga", 0) >= 2
            else max(largest, key=largest.get) if largest else None
        )
        if reference is None:
            return None, None, []

        best_run = None
        best_score = 0
        for run in runs:
            spreads = self._spread_map(run)
            reference_values = spreads.get(reference, [])
            if len(reference_values) < 2:
                continue
            score = max(
                (min(len(reference_values), len(values)) for code, values in spreads.items()
                 if code != reference and len(values) >= 2),
                default=0,
            )
            if score > best_score:
                best_score = score
                best_run = run

        if best_run is None:
            return reference, None, []
        return reference, best_run, sorted(self._spread_map(best_run))

    def _spread_map(self, run: Dict[str, Any]) -> Dict[str, List[float]]:
        """Returns per-repetition spreads, only when the counts line up.

        Some runs store hundreds of Monte-Carlo validation samples while
        ``runs`` is 1.  Those are not independent algorithm repetitions, so
        they must not be used as paired observations in a significance test.
        """
        repetitions = _number(run.get("runs"))
        result: Dict[str, List[float]] = {}
        for row in self._run_rows(run, 0):
            code = str(row.get("code", "")).lower()
            if not code:
                continue
            values = _spreads_for(run, row)
            if not values:
                continue
            if repetitions is not None and repetitions > 0:
                if len(values) != int(repetitions):
                    continue
            result[code] = values
        return result

    def _wilcoxon_rows(self, run: Dict[str, Any], reference: str) -> Tuple[List[Dict[str, Any]], str]:
        spreads = self._spread_map(run)
        reference_values = spreads.get(reference, [])
        if len(reference_values) < 2:
            return [], "Cần ít nhất 2 lần chạy lặp lại cho thuật toán tham chiếu."

        names = {
            str(row.get("code", "")).lower(): row.get("algorithm", row.get("name", "N/A"))
            for row in self._run_rows(run, 0)
        }
        rows: List[Dict[str, Any]] = []
        for code, values in spreads.items():
            if code == reference:
                continue
            n = min(len(reference_values), len(values))
            if n < 2:
                continue

            pairs_a = reference_values[:n]
            pairs_b = values[:n]
            differences = [a - b for a, b in zip(pairs_a, pairs_b)]
            statistic = None
            p_value = None

            if all(abs(difference) < 1e-12 for difference in differences):
                conclusion = "Không có khác biệt"
                color = SUBTEXT_FG
            elif _wilcoxon is None:
                conclusion = "Thiếu SciPy"
                color = SUBTEXT_FG
            else:
                try:
                    result = _wilcoxon(pairs_a, pairs_b, alternative="two-sided")
                    statistic = _number(result.statistic)
                    p_value = _number(result.pvalue)
                    conclusion = "Chờ hiệu chỉnh"
                    color = SUBTEXT_FG
                except Exception as error:
                    conclusion = f"Không thể kiểm định: {error}"
                    color = SUBTEXT_FG

            rows.append({
                "code": code,
                "name": names.get(code, code),
                "n": n,
                "statistic": statistic,
                "p_value": p_value,
                "p_holm": None,
                "conclusion": conclusion,
                "color": color,
            })

        # Holm correction over every computed p-value.
        tested = [row for row in rows if row["p_value"] is not None]
        tested.sort(key=lambda row: row["p_value"])
        running = 0.0
        total = len(tested)
        for index, row in enumerate(tested):
            adjusted = min(1.0, (total - index) * row["p_value"])
            running = max(running, adjusted)
            row["p_holm"] = running

        for row in rows:
            p_value = row["p_holm"]
            if p_value is None:
                continue
            if p_value < ALPHA:
                row["conclusion"] = "Khác biệt có ý nghĩa"
                row["color"] = GREEN
            else:
                row["conclusion"] = "Chưa đủ ý nghĩa"
                row["color"] = ORANGE

        rows.sort(
            key=lambda row: (
                row["p_holm"] is None,
                row["p_holm"] if row["p_holm"] is not None else 1.0,
            )
        )
        return rows, ""

